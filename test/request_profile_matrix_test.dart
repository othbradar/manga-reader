import 'dart:convert';
import 'dart:typed_data';

import 'package:copymanga_reader/services/copy_api_protocol.dart';
import 'package:copymanga_reader/services/copy_api_transport.dart';
import 'package:dio/dio.dart';
import 'package:flutter_test/flutter_test.dart';

import 'fixtures/copy_request_identity.dart';

class _WireAdapter implements HttpClientAdapter {
  final calls = <RequestOptions>[];
  final bodies = <RequestOptions, String>{};
  @override
  Future<ResponseBody> fetch(
    RequestOptions options,
    Stream<Uint8List>? body,
    Future<void>? cancelFuture,
  ) async {
    calls.add(options);
    if (body != null) {
      bodies[options] = utf8.decode(await body.expand((x) => x).toList());
    }
    if (options.uri.host == 'cdn.example') {
      return ResponseBody.fromBytes([1, 2, 3], 200);
    }
    return ResponseBody.fromString(
      jsonEncode({
        'code': 200,
        'results': {'api': [], 'list': [], 'total': 0},
      }),
      200,
      headers: {
        Headers.contentTypeHeader: [Headers.jsonContentType],
      },
    );
  }

  @override
  void close({bool force = false}) {}
}

void main() {
  late _WireAdapter adapter;
  late CopyApiTransport transport;
  late DateTime now;
  setUp(() {
    now = DateTime.utc(2026, 7, 29, 12, 34, 56);
    adapter = _WireAdapter();
    transport =
        CopyApiTransport(
            dio: Dio()..httpClientAdapter = adapter,
            requestClock: () => now,
            accountRequestInterval: Duration.zero,
          )
          ..setDeviceIdentity(fixtureDeviceIdentity)
          ..setApiDomain('content.example')
          ..setAuthenticationDomain('account.example')
          ..setToken('fixture-member-token');
  });

  test(
    'every implemented API entry uses the same recovered normal profile',
    () async {
      final cases = <(String, Map<String, dynamic>?)>[
        (
          CopyApiProtocol.searchPath,
          CopyApiProtocol.searchQuery(keyword: '漫画', limit: 20, offset: 0),
        ),
        (
          CopyApiProtocol.novelSearchPath,
          CopyApiProtocol.searchQuery(keyword: '小说', limit: 20, offset: 0),
        ),
        (
          CopyApiProtocol.comicDetailsPath('fixture'),
          CopyApiProtocol.comicDetailsQuery(inMainland: false),
        ),
        (
          CopyApiProtocol.novelDetailsPath('fixture'),
          CopyApiProtocol.comicDetailsQuery(inMainland: false),
        ),
        (
          CopyApiProtocol.groupChaptersPath('fixture', 'default'),
          CopyApiProtocol.groupChaptersQuery(limit: 100, offset: 0),
        ),
        (
          CopyApiProtocol.chapterContentPath('fixture', 'chapter-id'),
          CopyApiProtocol.chapterContentQuery(inMainland: false),
        ),
        (CopyApiProtocol.novelVolumesPath('fixture'), null),
        (CopyApiProtocol.novelVolumePath('fixture', 'volume-id'), null),
        (CopyApiProtocol.profilePath, null),
        (
          CopyApiProtocol.favoritesPath,
          CopyApiProtocol.favoritesQuery(
            limit: 18,
            offset: 0,
            ordering: '-datetime_updated',
          ),
        ),
        (
          CopyApiProtocol.novelFavoritesPath,
          CopyApiProtocol.favoritesQuery(
            limit: 18,
            offset: 0,
            ordering: '-datetime_updated',
          ),
        ),
      ];
      for (final entry in cases) {
        final member = CopyApiProtocol.requiresAuthentication(entry.$1);
        await transport.requestResults(
          entry.$1,
          query: entry.$2,
          authenticated: member,
        );
        final r = adapter.calls.last;
        expect(r.uri.host, member ? 'account.example' : 'content.example');
        expect(r.queryParameters, {...?entry.$2, 'platform': 3});
        expect(r.data, isNull);
      }
      await transport.requestResults(
        CopyApiProtocol.loginPath,
        method: 'POST',
        data: CopyApiProtocol.loginBody(
          'fixture-name',
          'fixture-password',
          salt: 4321,
        ),
      );
      await transport.requestResults(
        CopyApiProtocol.comicCollectPath,
        method: 'POST',
        authenticated: true,
        data: CopyApiProtocol.comicCollectBody('comic-id', true),
      );
      await transport.requestResults(
        CopyApiProtocol.novelCollectPath,
        method: 'POST',
        authenticated: true,
        data: CopyApiProtocol.novelCollectBody('book-id', true),
      );

      // Golden from independently recovered AOT/DEX, not generated by the builder.
      for (final r in adapter.calls) {
        final member = CopyApiProtocol.requiresAuthentication(r.uri.path);
        final account = member || r.uri.path == CopyApiProtocol.loginPath;
        final expected = {
          'Accept': 'application/json',
          'platform': '3',
          'source': 'copyApp',
          'version': '3.0.9',
          'webp': '1',
          'versionCode': '83',
          'referer': 'com.copymanga.app-3.0.9',
          'Accept-Language': '',
          'device': 'BUILD.FIXTURE.001',
          'deviceInfo': 'Fixture Model-fixture_device',
          'pseudoID': 'Ab12Cd34Ef56Gh78',
          'User-Agent': 'COPY/3.0.9',
          'authorization': member ? 'Token fixture-member-token' : 'Token ',
          'dt': '2026.07.29',
          'X-Auth-Timestamp': '1785328496',
          'X-Auth-Signature':
              '48f772e76c034d8281f1cab1bc52f5d25597ad1c6ed44642780b5d7e94954471',
          'umString': 'b4c89ca4104ea9a97750314d791520ac',
        };
        for (final entry in expected.entries) {
          expect(
            r.headers[entry.key],
            entry.value,
            reason: '${r.uri.path}: ${entry.key}',
          );
        }
        expect(r.headers['region'], account ? '0' : anyOf('0', '1'));
        final headerKeys = r.headers.keys.map((x) => x.toLowerCase()).toSet()
          ..remove('content-type')
          ..remove('content-length');
        expect(headerKeys, {
          ...expected.keys.map((x) => x.toLowerCase()),
          'region',
        });
        expect(r.queryParameters['platform'], 3);
        if (!member) {
          expect(
            r.headers.values,
            isNot(contains('Token fixture-member-token')),
          );
        }
        if (account) expect(r.followRedirects, isFalse);
        if (r.method == 'POST') {
          final body = Uri.splitQueryString(adapter.bodies[r]!);
          expect(r.contentType, Headers.formUrlEncodedContentType);
          expect(body['authorization'], expected['authorization']);
          expect(body['tapString'], '3af08590311032efe0660550a0563a53');
          expect(body['umString'], expected['umString']);
          expect(body['dt'], '2026-07-29 20:34:56.000Z');
          expect(body['isGoogle'], 'false');
          expect(body['androidId'], expected['device']);
          expect(body['buildTime'], '2025.05.22');
          if (member) {
            if (r.uri.path == CopyApiProtocol.comicCollectPath) {
              expect(body['comic_id'], 'comic-id');
              expect(body.containsKey('book_id'), isFalse);
            } else {
              expect(body['book_id'], 'book-id');
              expect(body.containsKey('comic_id'), isFalse);
            }
            expect(body['is_collect'], '1');
          } else {
            expect(
              body['password'],
              base64Encode(utf8.encode('fixture-password-4321')),
            );
            expect(body['salt'], '4321');
          }
        }
      }
      final network = adapter.calls.where(
        (r) => r.uri.path == CopyApiProtocol.networkPath,
      );
      expect(network, isNotEmpty);
      for (final r in network) {
        expect(r.queryParameters, {'platform': 3});
        expect(r.headers['authorization'], 'Token ');
      }
    },
  );

  test(
    'dt stays at initialization; request timestamp changes across midnight',
    () async {
      await transport.requestResults(CopyApiProtocol.searchPath);
      final first = adapter.calls.last;
      now = now.add(const Duration(days: 2));
      await transport.requestResults(CopyApiProtocol.searchPath);
      final second = adapter.calls.last;
      expect(second.headers['dt'], first.headers['dt']);
      expect(second.headers['X-Auth-Timestamp'], '1785501296');
      expect(
        second.headers['X-Auth-Signature'],
        isNot(first.headers['X-Auth-Signature']),
      );
    },
  );

  test(
    'CDN cover, page, avatar, illustration and TXT have no API headers',
    () async {
      await transport.requestResults(
        CopyApiProtocol.profilePath,
        authenticated: true,
      );
      for (final name in [
        'cover.jpg',
        'page.webp',
        'avatar.png',
        'illustration.jpg',
        'volume.txt',
      ]) {
        await transport.imageBytes('https://cdn.example/$name');
        final r = adapter.calls.last;
        expect(r.headers, isEmpty);
        expect(r.queryParameters, isEmpty);
        expect(r.data, isNull);
      }
    },
  );

  test(
    'wrong authentication classification and account method fail before any I/O',
    () async {
      for (final operation in [
        () => transport.requestResults(
          CopyApiProtocol.searchPath,
          authenticated: true,
        ),
        () => transport.requestResults(CopyApiProtocol.profilePath),
        () => transport.requestResults(
          CopyApiProtocol.loginPath,
          method: 'POST',
          authenticated: true,
        ),
        () => transport.requestResults(
          CopyApiProtocol.novelCollectPath,
          authenticated: true,
        ),
        () => transport.requestResults('https://cdn.example/file'),
      ]) {
        await expectLater(operation(), throwsA(isA<CopyApiException>()));
      }
      expect(adapter.calls, isEmpty);
    },
  );

  test(
    'missing native identity never sends a shared fake ID to the server',
    () async {
      transport.setDeviceIdentity(CopyDeviceIdentity.fallback);
      await expectLater(
        transport.requestResults(CopyApiProtocol.searchPath),
        throwsA(isA<CopyApiException>()),
      );
      await expectLater(
        transport.refreshDynamicDomains(),
        throwsA(isA<CopyApiException>()),
      );
      expect(adapter.calls, isEmpty);
      // Offline/resource reading is not coupled to API initialization.
      expect(await transport.imageBytes('https://cdn.example/page.jpg'), [
        1,
        2,
        3,
      ]);
    },
  );
}
